import { createRequire } from 'node:module';
import path from 'node:path';

// The pre-commit hook (.pre-commit-config.yaml) runs eslint from its own node environment,
// without this project's node_modules (e.g. on pre-commit.ci). It lists that environment in
// NODE_PATH, which `import` ignores: resolve the plugins from there as a fallback.
const require = createRequire(import.meta.url);
const searchPaths = [
	import.meta.dirname,
	...(process.env.NODE_PATH ?? '').split(path.delimiter).filter(Boolean)
];
const load = (name) => require(require.resolve(name, { paths: searchPaths }));

const js = load('@eslint/js');
const ts = load('typescript-eslint');
const svelte = load('eslint-plugin-svelte');
const prettier = load('eslint-config-prettier');
const globals = load('globals');

/** @type {import('eslint').Linter.Config[]} */
export default [
	js.configs.recommended,
	...ts.configs.recommended,
	...svelte.configs['flat/recommended'],
	prettier,
	...svelte.configs['flat/prettier'],
	{
		languageOptions: {
			globals: {
				...globals.browser,
				...globals.node
			}
		}
	},
	{
		files: ['**/*.svelte'],
		languageOptions: {
			parserOptions: {
				parser: ts.parser
			}
		}
	},
	{
		ignores: [
			'build/',
			'.svelte-kit/',
			'dist/',
			'.vercel/',
			'.pnpm-store/',
			'coverage/',
			'playwright-report/',
			'test-results/',
			// generated by typesafe-i18n
			'src/i18n/i18n-*.ts',
			// vendored shadcn-svelte components
			'src/lib/components/ui/',
			'src/lib/components/table/'
		]
	},
	{
		rules: {
			'@typescript-eslint/no-unused-expressions': 'off',
			// intentionally empty `catch {}` blocks (and their unused error) are fine
			'no-empty': ['error', { allowEmptyCatch: true }],
			'@typescript-eslint/no-unused-vars': [
				'error',
				{
					caughtErrors: 'none',
					// `_name` marks an intentionally unused parameter or destructured value
					argsIgnorePattern: '^_',
					varsIgnorePattern: '^_',
					destructuredArrayIgnorePattern: '^_'
				}
			],
			// {@html} only renders texts of our own translations (src/i18n), never user input
			'svelte/no-at-html-tags': 'off'
		}
	},
	{
		// TypeScript checks undefined names itself; `no-undef` does not know type namespaces
		// (https://typescript-eslint.io/troubleshooting/faqs/eslint#i-get-errors-from-the-no-undef-rule-about-global-variables-not-being-defined-even-though-there-are-no-typescript-errors)
		files: ['**/*.ts', '**/*.svelte'],
		rules: {
			'no-undef': 'off'
		}
	}
];
